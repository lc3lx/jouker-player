function countrySkinRows() {
  return COUNTRY_SKINS.map((s, i) => ({
    type: "avatar_frame",
    name: s.name,
    assetKey: s.assetKey,
    price: 2500,
    rarity: i < 3 ? "epic" : i < 8 ? "rare" : "common",
    isActive: true,
    featured: i < 4,
    featuredOrder: i,
    /** Public URL path under /assets/ (served from backend/assets). */
    previewImage: s.file,
    promoMeta: { skinFile: s.file },
  }));
}

